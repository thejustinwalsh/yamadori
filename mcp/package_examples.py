def manifest_rows(did: str) -> list[dict]:
    import onboarding
    p = os.path.join(onboarding.out_dir(did), MANIFEST)
    out = []
    try:
        with open(p, encoding="utf-8") as f:
            for ln in f:
                ln = ln.strip()
                if ln:
                    out.append(json.loads(ln))
    except (OSError, ValueError):
        return []
    return out


def manifests() -> list[tuple[str, str]]:
    """[(onboarding id, manifest path)] for every onboarding with one."""
    import onboarding
    root = onboarding.root()
    out = []
    try:
        names = sorted(os.listdir(root))
    except OSError:
        return []
    for did in names:
        p = os.path.join(root, did, MANIFEST)
        if os.path.isfile(p):
            out.append((did, p))
    return out


def manifest_sha256(did: str) -> str | None:
    import onboarding
    try:
        with open(os.path.join(onboarding.out_dir(did), MANIFEST), "rb") as f:
            return hashlib.sha256(f.read()).hexdigest()
    except OSError:
        return None


